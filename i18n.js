window.FAC_I18N_DEFAULT_LANG = 'fr';
window.FAC_I18N_LANGS = ['fr', 'en', 'it'];

(function () {
  function getTranslation(key, lang) {
    var entry = window.FAC_I18N[key];
    if (!entry) return null;
    return entry[lang] || entry[window.FAC_I18N_DEFAULT_LANG] || null;
  }

  function applyLanguage(lang) {
    if (window.FAC_I18N_LANGS.indexOf(lang) === -1) lang = window.FAC_I18N_DEFAULT_LANG;

    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var val = getTranslation(el.getAttribute('data-i18n'), lang);
      if (val !== null) el.innerHTML = val;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var val = getTranslation(el.getAttribute('data-i18n-placeholder'), lang);
      if (val !== null) el.setAttribute('placeholder', val);
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
      var val = getTranslation(el.getAttribute('data-i18n-alt'), lang);
      if (val !== null) el.setAttribute('alt', val);
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
      var val = getTranslation(el.getAttribute('data-i18n-aria-label'), lang);
      if (val !== null) el.setAttribute('aria-label', val);
    });

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      var isActive = btn.getAttribute('data-lang') === lang;
      btn.classList.toggle('is-active', isActive);
      btn.setAttribute('aria-pressed', String(isActive));
    });

    try { localStorage.setItem('fac-lang', lang); } catch (e) { /* stockage indisponible */ }
  }

  function initLanguage() {
    var saved = null;
    try { saved = localStorage.getItem('fac-lang'); } catch (e) { /* stockage indisponible */ }

    var lang = saved;
    if (!lang) {
      var browserLang = (navigator.language || 'fr').slice(0, 2).toLowerCase();
      lang = window.FAC_I18N_LANGS.indexOf(browserLang) !== -1 ? browserLang : window.FAC_I18N_DEFAULT_LANG;
    }
    applyLanguage(lang);

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.addEventListener('click', function () {
        applyLanguage(btn.getAttribute('data-lang'));
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLanguage);
  } else {
    initLanguage();
  }
})();
